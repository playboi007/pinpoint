import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:pinpoint/src/bridge/agent_guide.dart';
import 'package:pinpoint/src/bridge/agent_instructions.dart';
import 'package:pinpoint/src/bridge/bridge_server.dart';
import 'package:pinpoint/src/bridge/package_version.dart';

/// The generated agent guide. Plain `test`: `testWidgets` replaces
/// `HttpClient`.
void main() {
  String flat(String text) => text.replaceAll(RegExp(r'\s+'), ' ');

  test('the version constant equals the version in pubspec.yaml', () {
    final pubspec = File('pubspec.yaml').readAsStringSync();
    final version = RegExp(
      r'^version:\s*(\S+)',
      multiLine: true,
    ).firstMatch(pubspec)!.group(1);
    expect(pinpointVersion, version);
  });

  group('stamp', () {
    test('every guide file starts its text with the version stamp', () {
      for (final file in guideFiles()) {
        expect(
          guideVersionOf(file.content),
          pinpointVersion,
          reason: file.path,
        );
        expect(
          file.content,
          contains('generated by `dart run pinpoint:setup` $pinpointVersion'),
          reason: file.path,
        );
      }
      for (final copy in guideCopies(AgentKind.values.toSet())) {
        expect(guideVersionOf(copy.content), pinpointVersion);
        expect(copy.content, contains('source: .pinpoint/'));
      }
    });

    test('the stamp sits after the frontmatter, never before it', () {
      for (final text in [
        renderSkill(),
        renderCursorRule(),
        for (final n in commandNames) renderCommand(n),
      ]) {
        expect(text, startsWith('---\n'));
        expect(
          text.indexOf('generated by'),
          greaterThan(text.indexOf('\n---\n')),
        );
      }
    });

    test('older versions are told apart from the current one', () {
      expect(guideIsOlder('0.0.0'), isTrue);
      expect(guideIsOlder(pinpointVersion), isFalse);
      expect(guideIsOlder('0.0.1', '0.0.2'), isTrue);
      expect(guideIsOlder('0.1.0', '0.0.9'), isFalse);
      expect(guideIsOlder('1.0.0', '0.9.9'), isFalse);
      expect(guideIsOlder('0.0.1-beta', '0.0.1'), isFalse);
      expect(guideIsOlder('weird', '0.0.1'), isTrue);
    });

    test('staleGuideLine says one thing, only for an older guide', () {
      final old = renderSkill().replaceFirst(
        '`dart run pinpoint:setup` $pinpointVersion',
        '`dart run pinpoint:setup` 0.0.0',
      );
      expect(
        staleGuideLine(old),
        'pinpoint: agent guide files are from 0.0.0; '
        'run dart run pinpoint:setup --refresh',
      );
      expect(staleGuideLine(renderSkill()), isNull);
      expect(staleGuideLine('no stamp here'), isNull);
    });
  });

  group('SKILL.md', () {
    test('frontmatter has name and description, and is valid YAML-ish', () {
      final text = renderSkill();
      final match = RegExp(
        r'^---\n(.*?)\n---\n',
        dotAll: true,
      ).firstMatch(text)!;
      final lines = match.group(1)!.split('\n');
      expect(lines, hasLength(2));
      expect(lines[0], 'name: pinpoint');
      expect(lines[1], startsWith('description: "'));
      expect(lines[1], endsWith('"'));
      // A double-quoted YAML string: decodes as the JSON string it looks like.
      final description =
          jsonDecode(lines[1].substring('description: '.length)) as String;
      expect(description, skillDescription);
      expect(description.length, lessThan(400));
      for (final word in ['Flutter', 'MCP', 'state_flow']) {
        expect(description, contains(word));
      }
    });

    test('has the pinned lifecycle, undo, privacy and fallback text', () {
      final text = flat(renderSkill());
      for (final part in [
        '`list_notes`',
        '`update_note` with status `inProgress`',
        'Open the Source file at the given line',
        'Run `flutter analyze`',
        'status `fixed`',
        'give changes: one {summary, files} for each separate change',
        'call `verify_note`',
        'The user accepts the note or reopens it',
        '"reopened" in its header',
        'do not make the undone changes again',
        '"Undo these changes yourself"',
        'get_note_diff gives the patch',
        'run_steps',
        'target queries',
        'why two values change together, or what changed a value, state_flow',
        'PinPoint.probe',
        'list_probes',
        'replay({tape})',
        'Never paste a token',
        "Do not read or search Pinpoint's own package source",
        'Do not start the bridge unless the user asks',
        'do not edit files in `.pinpoint/` by hand',
        '`.pinpoint/open/*.md`',
        '`.pinpoint/config.json`',
        '.pinpoint/tools.md',
      ]) {
        expect(text, contains(part));
      }
    });

    test('shares its sentences with the MCP and CLAUDE.md text', () {
      final skill = flat(renderSkill());
      final section = flat(agentInstructions());
      for (final line in [
        changeLabelsLine,
        undoLine,
        reopenedLine,
        finishInNotesLine,
        operateLine,
        readTraceLine,
        probeLine,
        tapeLine,
      ]) {
        expect(skill, contains(flat(line)));
      }
      expect(section, contains(flat(changeLabelsLine)));
      expect(section, contains(flat(undoLine)));
    });

    test('is calm: no shouting, no OS commands, no background start', () {
      for (final text in [
        renderSkill(),
        for (final n in commandNames) renderCommand(n),
        renderGuideReadme(),
      ]) {
        for (final bad in [
          'MANDATORY',
          'CRITICAL',
          'nohup',
          'curl.exe',
          'PowerShell',
        ]) {
          expect(text, isNot(contains(bad)));
        }
      }
    });

    test('names the folder it is given', () {
      expect(renderSkill(dir: 'notes'), contains('`notes/tools.md`'));
      expect(renderSkill(dir: 'notes'), isNot(contains('.pinpoint/')));
    });
  });

  test('the Cursor rule has the three rule fields and the skill body', () {
    final text = renderCursorRule();
    expect(text, startsWith('---\ndescription: "'));
    expect(text, contains('\nglobs:\nalwaysApply: false\n---\n'));
    expect(text, contains(skillBody()));
  });

  group('commands', () {
    test('three commands, each short and pointing to SKILL.md', () {
      expect(commandNames, [
        'pinpoint-fix-notes',
        'pinpoint-check',
        'pinpoint-state',
      ]);
      for (final name in commandNames) {
        final text = renderCommand(name);
        expect(text, startsWith('---\ndescription: "'), reason: name);
        expect(text, contains('.pinpoint/SKILL.md'), reason: name);
        expect(text.split('\n').length, lessThan(25), reason: name);
      }
      expect(renderCommand('pinpoint-state'), contains('argument-hint'));
      expect(() => renderCommand('nope'), throwsArgumentError);
    });

    test('check does not start the bridge and reads config.json', () {
      final text = flat(renderCommand('pinpoint-check'));
      expect(text, contains('Do not start the bridge yourself'));
      expect(text, contains('.pinpoint/config.json'));
      expect(text, contains('list_notes'));
      expect(text, contains('dart run pinpoint:bridge'));
    });

    test('state uses state_flow twice and explains the story', () {
      final text = flat(renderCommand('pinpoint-state'));
      expect(text, contains('`state_flow`'));
      expect(text, contains('then call `state_flow` again'));
      expect(text, contains('Tell the story in plain words'));
    });

    test('fix-notes works all open notes', () {
      final text = flat(renderCommand('pinpoint-fix-notes'));
      expect(text, contains('Call `list_notes`'));
      expect(text, contains('"Work a note"'));
    });
  });

  test('README names every folder and file, and how to refresh', () {
    final text = renderGuideReadme();
    for (final part in [
      'private and git-ignored',
      'SKILL.md',
      'commands/',
      'tools.md',
      'mcp.json',
      'config.json',
      'open/',
      'resolved/',
      'drafts/',
      'tmp/',
      'tapes/',
      'runs/',
      'undo/',
      'vm-service.txt',
      'Data (private, never share)',
      'dart run pinpoint:setup --refresh',
    ]) {
      expect(text, contains(part));
    }
  });

  group('tools.md', () {
    late Directory project;
    late PinPointBridge bridge;

    setUp(() async {
      project = await Directory.systemTemp.createTemp('pinpoint_guide_');
      bridge = await PinPointBridge.start(
        dir: '${project.path}/.pinpoint',
        port: 0,
      );
    });
    tearDown(() async {
      await bridge.close();
      await project.delete(recursive: true);
    });

    /// What the running MCP server answers to `tools/list`.
    Future<List<Map<String, Object?>>> served() async {
      final client = HttpClient();
      try {
        final request = await client.postUrl(
          Uri.parse('http://127.0.0.1:${bridge.port}/mcp'),
        );
        request.headers.contentType = ContentType.json;
        request.write(
          jsonEncode({'jsonrpc': '2.0', 'id': 1, 'method': 'tools/list'}),
        );
        final response = await request.close();
        final body =
            jsonDecode(await utf8.decodeStream(response))
                as Map<String, Object?>;
        return [
          for (final t
              in (body['result']! as Map<String, Object?>)['tools']!
                  as List<Object?>)
            t! as Map<String, Object?>,
        ];
      } finally {
        client.close(force: true);
      }
    }

    test('lists every tool the running MCP server serves', () async {
      final tools = await served();
      final text = renderToolsDoc();
      expect(tools.length, greaterThan(30));
      for (final tool in tools) {
        final name = tool['name']! as String;
        expect(text, contains('| `$name` |'), reason: name);
      }
      // And nothing else: as many rows as served tools.
      final rows = RegExp(r'^\| `', multiLine: true).allMatches(text).length;
      expect(rows, tools.length);
      expect(text, contains('serves ${tools.length} MCP tools'));
    });

    test('every tool is in a group (no "Other" table)', () {
      expect(renderToolsDoc(), isNot(contains('## Other')));
      for (final group in toolGroups.values) {
        for (final name in group) {
          expect(
            allToolDefinitions().map((t) => t['name']),
            contains(name),
            reason: 'group names a tool that does not exist: $name',
          );
        }
      }
    });

    test('a row has its description and inputs from the definition', () async {
      final text = renderToolsDoc();
      final line = text
          .split('\n')
          .firstWhere((l) => l.startsWith('| `update_note`'));
      expect(line, contains('Bridge'));
      expect(line, contains('`id` (required)'));
      expect(line, contains('`changes`'));
      expect(
        text.split('\n').firstWhere((l) => l.startsWith('| `state_flow`')),
        contains('In app'),
      );
      expect(
        text.split('\n').firstWhere((l) => l.startsWith('| `back`')),
        contains('none'),
      );
    });

    test('a tool without a group goes to "Other"', () {
      final text = renderToolsDoc(
        tools: [
          ...allToolDefinitions(),
          {
            'name': 'brand_new',
            'description': 'A new tool. More words.',
            'inputSchema': {
              'type': 'object',
              'properties': {'a': <String, Object?>{}},
            },
          },
        ],
      );
      expect(text, contains('## Other'));
      expect(text, contains('| `brand_new` | Bridge | A new tool. | `a` |'));
    });
  });

  group('MCP entries', () {
    test('each agent gets the form it reads', () {
      const url = 'http://127.0.0.1:4800/mcp';
      expect(mcpEntryFor(AgentKind.claude, 4800), {'type': 'http', 'url': url});
      expect(mcpEntryFor(AgentKind.cursor, 4800), {'url': url});
      expect(mcpEntryFor(AgentKind.vscode, 4800), {'type': 'http', 'url': url});
      expect(mcpEntryFor(AgentKind.agents, 4800), isNull);
    });

    test('files and keys', () {
      final files = mcpFiles(AgentKind.values.toSet(), 4747);
      expect(
        {for (final f in files) f.path: f.serversKey},
        {
          '.mcp.json': 'mcpServers',
          '.cursor/mcp.json': 'mcpServers',
          '.vscode/mcp.json': 'servers',
        },
      );
      expect(mcpFiles({AgentKind.agents}, 4747), isEmpty);
    });
  });

  test('copies: where each agent looks', () {
    final all = guideCopies(AgentKind.values.toSet());
    expect(
      [for (final c in all) c.path],
      [
        '.claude/skills/pinpoint/SKILL.md',
        '.claude/commands/pinpoint-fix-notes.md',
        '.claude/commands/pinpoint-check.md',
        '.claude/commands/pinpoint-state.md',
        '.cursor/rules/pinpoint.mdc',
      ],
    );
    expect(guideCopies({AgentKind.vscode, AgentKind.agents}), isEmpty);
  });
}
