/// The agents setup can write for. `agents` is the generic `AGENTS.md`.
enum AgentKind {
  claude,
  cursor,
  vscode,
  agents;

  /// The name as `--agents` takes it.
  String get flag => name;

  /// A name for people.
  String get label => switch (this) {
    claude => 'Claude Code',
    cursor => 'Cursor',
    vscode => 'VS Code',
    agents => 'AGENTS.md',
  };
}

/// One generated file: [path] is relative to the folder it is written in.
class GuideFile {
  const GuideFile(this.path, this.content);

  final String path;
  final String content;
}

/// The `name` of the skill.
const String skillName = 'pinpoint';

/// The `description` of the skill: when an agent should load it.
const String skillDescription =
    'Use when the user sends UI feedback notes from a running Flutter app '
    '(Pinpoint), when the Pinpoint MCP tools (list_notes, update_note, '
    'state_flow) are connected, or when the user asks why a value or widget '
    'changed in the app.';

/// The names of the three commands, in the order they are listed.
const List<String> commandNames = [
  'pinpoint-fix-notes',
  'pinpoint-check',
  'pinpoint-state',
];

final RegExp _stampPattern = RegExp(
  r'generated by `dart run pinpoint:setup` (\S+?)[;\s]',
);

/// The line every generated guide file carries. [source] names the file a
/// copy comes from.
String generatedStamp({String? source}) =>
    '<!-- generated by `dart run pinpoint:setup` $pinpointVersion'
    '${source == null ? '' : ' (source: $source)'}; '
    'edits are lost on --refresh. -->';

/// The version a generated [text] was written by, or null when it has no
/// stamp.
String? guideVersionOf(String text) => _stampPattern.firstMatch(text)?.group(1);

/// Whether [found] is older than [current]; a version that cannot be
/// compared counts as older when it differs.
bool guideIsOlder(String found, [String current = pinpointVersion]) {
  if (found == current) return false;
  return switch ((_numbers(found), _numbers(current))) {
    (final a?, final b?) => _compare(a, b) < 0,
    _ => true,
  };
}

List<int>? _numbers(String version) {
  final parts = [
    for (final part in version.split(RegExp(r'[-+]')).first.split('.'))
      int.tryParse(part),
  ];
  return parts.contains(null) ? null : [...parts.nonNulls];
}

int _compare(List<int> a, List<int> b) {
  for (var i = 0; i < a.length || i < b.length; i++) {
    final order = (i < a.length ? a[i] : 0).compareTo(i < b.length ? b[i] : 0);
    if (order != 0) return order;
  }
  return 0;
}

/// The line the bridge logs at start when [skillText] (the guide's
/// `SKILL.md`) is from an older version; null when it is current or has no
/// stamp.
String? staleGuideLine(String skillText) => switch (guideVersionOf(skillText)) {
  final found? when guideIsOlder(found) =>
    'pinpoint: agent guide files are from $found; '
        'run dart run pinpoint:setup --refresh',
  _ => null,
};

/// The body of the skill (after the frontmatter) for notes kept in [dir].
String skillBody({String dir = '.pinpoint'}) =>
    '''
# Pinpoint

Pinpoint sends feedback from a running Flutter app to you as notes. A note holds the user's comment, the widget's source file and line, its layout and a screenshot. You change the code and say what you did. The user checks it in the app.

Use the Pinpoint MCP tools when they are connected. All tools are listed in `$dir/tools.md`.

## Work a note

1. `list_notes` shows the open notes. Drafts are never listed.
2. `get_note` gives one note, with its screenshot.
3. `update_note` with status `inProgress`.
4. Open the Source file at the given line. Read the comment. Look at the screenshot.
5. Make the change.
6. Run `flutter analyze`. If the app runs, `hot_reload` puts the change in it.
7. `update_note` with status `fixed` and a one-line message that says what you did. Use `rejected` with the reason when you will not make the change.
8. If the note has checks, call `verify_note`.
9. The user accepts the note or reopens it.

$changeLabelsLine
$finishInNotesLine

## Reopened notes and undo

$reopenedLine

$undoLine Do not undo changes the user did not ask you to undo. Files you did not name in `changes` show as "other" in the user's list.

## Operate the app

$operateLine

These tools need "Allow agent control" on in the app. If a tool is refused for that reason, ask the user to turn it on.

## Investigate

- $readTraceLine
- `state_flow` opens a window on its first call. Act in the app (or with `tap`), then call it again to read the story.
- $probeLine
- $tapeLine

## Privacy

Pinpoint masks secrets (header values, URL parameters, hidden text fields) before it stores them. Do not try to get them back. Never paste a token, a cookie or a value from a redacted field into code, chat or a commit. Tapes hold real request and response bodies: read them only through the tools.

## Do not

- Do not read or search Pinpoint's own package source. The tools and this file say what you need.
- Do not start the bridge unless the user asks. If it is not running, say so and tell the user to run `dart run pinpoint:bridge` in the app folder.
- With MCP, do not edit files in `$dir/` by hand. One exception: to restore a deleted note, move its files from `$dir/tmp/<id>__<time>/` back to `$dir/open/`.
- Do not touch `$dir/drafts/`. Drafts are not sent yet.

## When MCP is not connected

Read `$dir/open/*.md`: each file is one note, with the Source file and line and the name of the PNG. Read `$dir/config.json` to see whether the bridge runs (`status`, `port`). To work a note without MCP: change the code, run `flutter analyze`, move the note's files (`<id>.md`, `<id>.json`, `<id>.png`) to `$dir/resolved/`, and add one line to the `.md` that says what you changed. The pin in the app updates when the bridge sees the move.
''';

/// `SKILL.md` for notes kept in [dir]: frontmatter, the stamp, the body.
String renderSkill({String dir = '.pinpoint', String? source}) =>
    '''
---
name: $skillName
description: ${_yamlString(skillDescription)}
---
${generatedStamp(source: source)}

${skillBody(dir: dir)}''';

/// The Cursor rule (`.cursor/rules/pinpoint.mdc`): the same body, with the
/// frontmatter Cursor reads. It is attached when the agent finds its
/// description fits (no globs, not always on).
String renderCursorRule({String dir = '.pinpoint', String? source}) =>
    '''
---
description: ${_yamlString(skillDescription)}
globs:
alwaysApply: false
---
${generatedStamp(source: source)}

${skillBody(dir: dir)}''';

String _yamlString(String text) =>
    '"${text.replaceAll(r'\', r'\\').replaceAll('"', r'\"')}"';

/// The command called [name] for notes kept in [dir].
String renderCommand(String name, {String dir = '.pinpoint', String? source}) {
  final (description, hint, body) = _commandSpec(name, dir);
  return '''
---
description: ${_yamlString(description)}
${hint == null ? '' : 'argument-hint: ${_yamlString(hint)}\n'}---
${generatedStamp(source: source)}

$body''';
}

/// The description, argument hint and body of the command [name].
(String, String?, String) _commandSpec(
  String name,
  String dir,
) => switch (name) {
  'pinpoint-fix-notes' => (
    'Work all open Pinpoint notes from the running app.',
    null,
    '''
Work every open Pinpoint note. Follow `$dir/SKILL.md` for how.

1. Call `list_notes`. If MCP is not connected, read `$dir/open/*.md` (see "When MCP is not connected" in `$dir/SKILL.md`).
2. If no note is open, say so and stop. Drafts are not sent yet: do not touch them.
3. Work the notes one at a time. For each note, do the steps of "Work a note" in `$dir/SKILL.md`.
4. At the end, give the user a short list: each note id, what you changed, and what they should check in the app.
''',
  ),
  'pinpoint-check' => (
    'Check that the Pinpoint bridge runs and the agent is connected to it.',
    null,
    '''
Check the Pinpoint setup. Follow `$dir/SKILL.md`. Do not start the bridge yourself.

1. Read `$dir/config.json`: `status`, `port`, `pid`, `startedAt`, `version`. If the file is not there, the bridge has not run in this folder.
2. Call `list_notes`. If it answers, tell the user: the bridge runs, its port, and how many notes are open.
3. If the tool is missing or fails, MCP is not connected. Tell the user to run `dart run pinpoint:bridge` in the app folder, and to run `dart run pinpoint:setup --write` if the MCP entry is missing. If `config.json` says `running` but the tools fail, the bridge may have stopped without a clean exit: say so.
4. If the stamp in `$dir/SKILL.md` ("generated by ... <version>") is older than `version` in `config.json`, tell the user to run `dart run pinpoint:setup --refresh`.
''',
  ),
  'pinpoint-state' => (
    'Explain why a value or widget changed in the running app, with state_flow.',
    '[widget or question]',
    '''
Explain why something changed in the app. Follow "Investigate" in `$dir/SKILL.md`.

1. Find the widget the user names (after the command, or in their question). If they named none, ask which widget.
2. Call `state_flow` with that widget as `target` (file, line, type, text or key). The first call opens a window.
3. Act in the app (ask the user to, or use `tap` or `run_steps`), then call `state_flow` again.
4. Tell the story in plain words: what the user did, which values changed, what changed them (file and line), and what rebuilt. Say what Pinpoint could not see (plain fields, a value set after an `await`).
''',
  ),
  _ => throw ArgumentError.value(name, 'name', 'Unknown command'),
};

/// `README.md` for the `.pinpoint/` folder (named [dir]).
String renderGuideReadme({String dir = '.pinpoint'}) =>
    '''
${generatedStamp()}

# $dir/

This folder is where Pinpoint keeps its files for this app: the notes you send, and the guide a coding agent reads.

**The folder is private and git-ignored** (`.gitignore` here holds `*`). Do not commit it. Do not share its data files: notes hold your comments and screenshots, tapes hold request and response bodies.

## Guide files

Generated by `dart run pinpoint:setup`. Safe to read, safe to refresh. Edits are lost on `--refresh`.

| Path | What it is |
| --- | --- |
| `README.md` | This file. |
| `SKILL.md` | How an agent works with Pinpoint: the note lifecycle, undo, investigation, privacy, what not to do. |
| `commands/` | `pinpoint-fix-notes.md`, `pinpoint-check.md`, `pinpoint-state.md`: short commands that point to `SKILL.md`. |
| `tools.md` | Every MCP tool with its inputs, made from the bridge's own definitions. |
| `mcp.json` | The MCP entry for the bridge (HTTP, `/mcp`). |
| `agent-instructions.md` | A short section for `CLAUDE.md` or `AGENTS.md`. |

## Live status

| Path | What it is |
| --- | --- |
| `config.json` | Written by the bridge: `status` (`running` or `stopped`), `port`, `pid`, `version`, `noteSchema`, `root`, `startedAt`, `endpoints`. It is status, not settings: options are bridge flags. After a crash it can still say `running`: call `list_notes` to be sure. |

## Data (private, never share)

| Path | What it is |
| --- | --- |
| `open/` | Notes that are submitted, in progress or fixed: `<id>.md`, `<id>.json`, `<id>.png`. The agent's work list. |
| `resolved/` | The same files for closed notes. |
| `drafts/` | Notes the user has not sent. No agent reads them. |
| `tmp/` | Deleted notes, flushed after at least 1 hour. |
| `tapes/` | Recorded runs, with request and response bodies. |
| `runs/` | Replay runs. |
| `undo/` | A temporary copy of the git index for undo checkpoints. |
| `vm-service.txt` | The app's debug service address, for `hot_reload`. |

## Refresh

After you update the Pinpoint package, run this in the app folder:

```bash
