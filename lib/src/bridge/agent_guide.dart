/// Every tool definition the MCP server can serve.
List<Map<String, Object?>> allToolDefinitions() => [
  ...McpServer.noteTools,
  McpServer.hotReloadTool,
  ...agentTools,
];

/// `tools.md`: one table for each group of [toolGroups], from [tools].
String renderToolsDoc({List<Map<String, Object?>>? tools}) {
  final all = tools ?? allToolDefinitions();
  final byName = {for (final t in all) t['name']! as String: t};
  final inApp = {for (final t in agentTools) t['name']! as String};
  final grouped = {for (final names in toolGroups.values) ...names};
  final groups = {
    ...toolGroups,
    'Other': [
      for (final name in byName.keys)
        if (!grouped.contains(name)) name,
    ],
  };
  return [
    generatedStamp(),
    '',
    '# Pinpoint tools',
    '',
    'The bridge serves ${all.length} MCP tools at `$mcpPath`. This list is '
        'made from the definitions it serves. "In app" tools run inside the '
        'running app and need "Allow agent control" on in the app. "Bridge" '
        'tools are answered by the bridge. Drafts are never visible to a '
        'tool. How to use them: `SKILL.md`.',
    for (final MapEntry(:key, :value) in groups.entries)
      ..._toolTable(key, [
        for (final name in value)
          if (byName[name] case final tool?) (tool, inApp.contains(name)),
      ]),
  ].join('\n');
}

List<String> _toolTable(String title, List<(Map<String, Object?>, bool)> rows) {
  if (rows.isEmpty) return const [];
  return [
    '',
    '## $title',
    '',
    '| Tool | Where | What it does | Key inputs |',
    '| --- | --- | --- | --- |',
    for (final (tool, inApp) in rows)
      '| `${tool['name']}` | ${inApp ? 'In app' : 'Bridge'} '
          '| ${_cell(_firstSentence('${tool['description']}'))} '
          '| ${_cell(_inputs(tool))} |',
    '',
  ];
}

String _cell(String text) => text.replaceAll('|', r'\|');

String _firstSentence(String description) {
  final text = description.replaceAll(RegExp(r'\s+'), ' ').trim();
  return RegExp(r'^(.*?[.!?])(?:\s|$)').firstMatch(text)?.group(1) ?? text;
}

String _inputs(Map<String, Object?> tool) {
  final schema = tool['inputSchema'];
  if (schema is! Map<String, Object?>) return 'none';
  final required = schema['required'] as List<Object?>? ?? const [];
  return switch (schema['properties']) {
    final Map<String, Object?> properties when properties.isNotEmpty => [
      for (final key in properties.keys)
        '`$key`${required.contains(key) ? ' (required)' : ''}',
    ].join(', '),
    _ => 'none',
  };
}

/// The MCP server entry for the bridge on [port] in the form [agent] reads;
/// null for an agent with no MCP file.
Map<String, Object?>? mcpEntryFor(AgentKind agent, int port) {
  final url = 'http://127.0.0.1:$port$mcpPath';
  return switch (agent) {
    AgentKind.claude || AgentKind.vscode => {'type': 'http', 'url': url},
    AgentKind.cursor => {'url': url},
    AgentKind.agents => null,
  };
}

/// The MCP file of [agent] (relative to the project) and the key that holds
/// its servers; null for an agent with no MCP file.
(String path, String serversKey)? _mcpLocation(AgentKind agent) =>
    switch (agent) {
      AgentKind.claude => ('.mcp.json', 'mcpServers'),
      AgentKind.cursor => ('.cursor/mcp.json', 'mcpServers'),
      AgentKind.vscode => ('.vscode/mcp.json', 'servers'),
      AgentKind.agents => null,
    };

/// An MCP config file of one agent with the `pinpoint` entry to put in it.
class McpFile {
  const McpFile(this.agent, this.path, this.serversKey, this.entry);

  final AgentKind agent;
  final String path;
  final String serversKey;
  final Map<String, Object?> entry;
}

/// The MCP files for [agents] on [port].
List<McpFile> mcpFiles(Set<AgentKind> agents, int port) => [
  for (final agent in AgentKind.values)
    if (agents.contains(agent))
      if (_mcpLocation(agent) case (final path, final key))
        McpFile(agent, path, key, mcpEntryFor(agent, port)!),
];

/// The guide files for `.pinpoint/` (paths relative to it), for notes kept
/// in [dir].
List<GuideFile> guideFiles({String dir = '.pinpoint'}) => [
  GuideFile('README.md', renderGuideReadme(dir: dir)),
  GuideFile('SKILL.md', renderSkill(dir: dir)),
  for (final name in commandNames)
    GuideFile('commands/$name.md', renderCommand(name, dir: dir)),
  GuideFile('tools.md', renderToolsDoc()),
];

/// A copy of a guide file where [agent] looks for it, relative to the
/// project folder.
class GuideCopy {
  const GuideCopy(this.agent, this.path, this.content);

  final AgentKind agent;
  final String path;
  final String content;
}

/// The copies `--write` makes for [agents], for notes kept in [dir].
List<GuideCopy> guideCopies(
  Set<AgentKind> agents, {
  String dir = '.pinpoint',
}) => [
  for (final agent in AgentKind.values)
    if (agents.contains(agent)) ..._copiesFor(agent, dir),
];

List<GuideCopy> _copiesFor(AgentKind agent, String dir) => switch (agent) {
  AgentKind.claude => [
    GuideCopy(
      agent,
      '.claude/skills/pinpoint/SKILL.md',
      renderSkill(dir: dir, source: '$dir/SKILL.md'),
    ),
    for (final name in commandNames)
      GuideCopy(
        agent,
        '.claude/commands/$name.md',
        renderCommand(name, dir: dir, source: '$dir/commands/$name.md'),
      ),
  ],
  AgentKind.cursor => [
    GuideCopy(
      agent,
      '.cursor/rules/pinpoint.mdc',
      renderCursorRule(dir: dir, source: '$dir/SKILL.md'),
    ),
  ],
  AgentKind.vscode || AgentKind.agents => const [],
};
